const AUTHOR = "أ. عَائِشَة البَرْوَانِيَّة";
const COPYRIGHT_YEAR = "٢٠٢٦";

/* ================= التطبيق الرئيسي ================= */
export default function App() {
  const [view, setView] = useState("welcome");
  const [profile, setProfile] = useState(null);
  const [storyId, setStoryId] = useState(null);
  const [pendingQuiz, setPendingQuiz] = useState(null);
  const [loading, setLoading] = useState(false);

  const handleStart = async (name) => {
    setLoading(true);
    const p = await loadProfile(name);
    setProfile(p);
    setLoading(false);
    setView("home");
  };

  const handleComplete = async (sId) => {
    if (!profile) return;
    const completed = profile.completed.includes(sId) ? profile.completed : [...profile.completed, sId];
    const newProfile = { ...profile, completed };
    setProfile(newProfile);
    await saveProfile(newProfile);

    const count = completed.length;
    const milestone = Math.floor(count / 3);
    if (milestone >= 1 && !newProfile.quizzesTaken.includes(milestone) && milestone <= quizSets.length) {
      setPendingQuiz(milestone);
      setView("quiz");
    } else {
      setView("stories");
    }
  };

  const handleQuizFinish = async () => {
    const newProfile = { ...profile, quizzesTaken: [...profile.quizzesTaken, pendingQuiz] };
    setProfile(newProfile);
    await saveProfile(newProfile);
    setPendingQuiz(null);
    setView("stories");
  };

  const currentStory = stories.find((s) => s.id === storyId);

  return (
    <div dir="rtl" style={{ fontFamily: "'Tajawal', sans-serif", background: "#EDE7DA" }} className="min-h-screen w-full flex flex-col items-center justify-center gap-3 p-4">
      <style>{`
        @keyframes bob { 0%,100% { transform: translateY(0px) rotate(-2deg);} 50% { transform: translateY(-10px) rotate(2deg);} }
        @keyframes twinkle { 0%,100% { opacity: .3;} 50% { opacity: 1;} }
        .turtle-bob { animation: bob 3.2s ease-in-out infinite; display:inline-block; }
        .star { animation: twinkle 2.4s ease-in-out infinite; }
      `}</style>

      {view === "welcome" && <Welcome onStart={handleStart} />}

      {view === "home" && profile && (
        <Home profile={profile} onOpenStories={() => setView("stories")} onOpenDictionary={() => setView("dictionary")} />
      )}

      {view === "stories" && profile && (
        <StoriesList profile={profile} onSelectStory={(id) => { setStoryId(id); setView("story"); }} onBack={() => setView("home")} />
      )}

      {view === "dictionary" && <Dictionary onBack={() => setView("home")} />}

      {view === "story" && currentStory && profile && (
        <StoryPlayer story={currentStory} studentName={profile.name} onComplete={handleComplete} onExit={() => setView("stories")} />
      )}

      {view === "quiz" && profile && pendingQuiz !== null && (
        <Quiz setIndex={pendingQuiz - 1} studentName={profile.name} onFinish={handleQuizFinish} />
      )}

      <footer
        style={{
          fontFamily: "'Tajawal', sans-serif", fontSize: 11.5, color: "#7A8577",
          textAlign: "center", lineHeight: 1.9, maxWidth: 384, paddingInline: 8,
        }}
      >
        © {COPYRIGHT_YEAR} {AUTHOR} — جَمِيعُ الحُقُوقِ مَحْفُوظَةٌ
      </footer>

      {loading && (
        <div className="fixed inset-0 flex items-center justify-center" style={{ background: "rgba(0,0,0,0.2)" }}>
          <Loader2 className="animate-spin" size={30} color="#fff" />
        </div>
      )}
    </div>
  );
}
