function Quiz({ setIndex, studentName, onFinish }) {
  const questions = quizSets[setIndex] || quizSets[0];
  const [i, setI] = useState(0);
  const [selected, setSelected] = useState(null);
  const [score, setScore] = useState(0);
  const [done, setDone] = useState(false);

  const q = questions[i];
  const options = q.type === "tf" ? ["صَحِيحٌ ✅", "خَطَأٌ ❌"] : q.options;

  const handleAnswer = (idx) => {
    if (selected !== null) return;
    setSelected(idx);
    const isCorrect = q.type === "tf" ? (idx === 0) === q.correct : idx === q.correct;
    if (isCorrect) setScore((s) => s + 1);
    setTimeout(() => {
      if (i + 1 < questions.length) { setI(i + 1); setSelected(null); }
      else setDone(true);
    }, 900);
  };

  return (
    <div className="relative w-full max-w-sm rounded-3xl overflow-hidden shadow-2xl" style={{ minHeight: 660, background: "linear-gradient(180deg,#FFF3D6 0%,#FFE0A8 100%)" }}>
      <div className="flex items-center justify-center gap-2 pt-6">
        <HelpCircle size={20} color="#8C6239" />
        <span style={{ fontFamily: "'Markazi Text', serif", fontWeight: 800, color: "#8C6239", fontSize: 16 }}>اِخْتِبَارُ المَعْلُومَاتِ البَيْئِيَّةِ</span>
      </div>
      <p style={{ textAlign: "center", color: "#A17A45", fontSize: 11.5, marginTop: 4 }}>سُؤَالٌ {Math.min(i + 1, questions.length)} مِنْ {questions.length}</p>

      {!done ? (
        <div className="px-5 mt-6">
          <div className="rounded-2xl p-4" style={{ background: "#fff", boxShadow: "0 8px 20px rgba(0,0,0,0.15)" }}>
            <p style={{ color: "#33301F", fontSize: 15, lineHeight: 1.9, fontWeight: 700 }}>{q.q}</p>
          </div>
          <div className="flex flex-col gap-3 mt-4">
            {options.map((opt, idx) => {
              let bg = "#fff", color = "#33301F";
              if (selected !== null) {
                const isCorrectIdx = q.type === "tf" ? (idx === 0) === q.correct : idx === q.correct;
                if (isCorrectIdx) { bg = "#DCEFE1"; color = "#1E6B45"; }
                else if (idx === selected) { bg = "#FBDCD3"; color = "#B33D24"; }
              }
              return (
                <button key={idx} onClick={() => handleAnswer(idx)} className="rounded-xl px-4 py-3 text-right font-bold flex items-center justify-between"
                  style={{ background: bg, color, fontFamily: "'Markazi Text', serif", fontSize: 14, boxShadow: "0 4px 10px rgba(0,0,0,0.1)" }}>
                  <span>{opt}</span>
                  {selected !== null && (q.type === "tf" ? (idx === 0) === q.correct : idx === q.correct) && <CheckCircle2 size={16} color="#1E6B45" />}
                  {selected === idx && !(q.type === "tf" ? (idx === 0) === q.correct : idx === q.correct) && <XCircle size={16} color="#B33D24" />}
                </button>
              );
            })}
          </div>
        </div>
      ) : (
        <div className="px-6 mt-10 flex flex-col items-center gap-4">
          <IconChip bg="#FFF3D6" size={72} radius={26}>
            <Glyph name="trophy" size={34} color="#8C6239" />
          </IconChip>
          <p style={{ fontFamily: "'Markazi Text', serif", color: "#8C6239", fontWeight: 800, fontSize: 18, textAlign: "center" }}>
            أَحْسَنْتَ يَا {studentName}!
          </p>
          <p style={{ color: "#5A5646", fontSize: 13.5 }}>حَصَلْتَ عَلَى {score} مِنْ {questions.length}</p>
          <button onClick={onFinish} className="rounded-xl px-6 py-2.5 font-bold" style={{ background: omanGreen, color: "#fff", fontFamily: "'Markazi Text', serif" }}>
            أُتَابِعُ المُغَامَرَةَ
          </button>
        </div>
      )}
    </div>
  );
}

