/* ================= أدوات التخزين =================
   يحفظ التقدّم في هذا الجهاز عبر localStorage.
   وإن كان التطبيق يعمل داخل بيئة Claude التي توفّر window.storage
   فإنه يستخدمها تلقائيًا بدلًا من ذلك. */
const STORAGE_PREFIX = "mughamarati:student:";
const emptyProfile = (name) => ({ name, completed: [], quizzesTaken: [], updatedAt: Date.now() });

async function loadProfile(name) {
  try {
    if (typeof window !== "undefined" && window.storage && typeof window.storage.get === "function") {
      const res = await window.storage.get(`student:${name}`, true);
      return res ? JSON.parse(res.value) : emptyProfile(name);
    }
    const raw = window.localStorage.getItem(STORAGE_PREFIX + name);
    if (!raw) return emptyProfile(name);
    const parsed = JSON.parse(raw);
    return {
      name,
      completed: Array.isArray(parsed.completed) ? parsed.completed : [],
      quizzesTaken: Array.isArray(parsed.quizzesTaken) ? parsed.quizzesTaken : [],
      updatedAt: parsed.updatedAt || Date.now(),
    };
  } catch (e) {
    return emptyProfile(name);
  }
}
async function saveProfile(profile) {
  const payload = { ...profile, updatedAt: Date.now() };
  try {
    if (typeof window !== "undefined" && window.storage && typeof window.storage.set === "function") {
      await window.storage.set(`student:${profile.name}`, JSON.stringify(payload), true);
      return;
    }
    window.localStorage.setItem(STORAGE_PREFIX + profile.name, JSON.stringify(payload));
  } catch (e) { /* تجاهل بصمت */ }
}
